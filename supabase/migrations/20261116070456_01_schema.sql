create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  email text,
  role text not null default 'employee' check (role in ('manager','employee')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.employee_permissions (
  user_id uuid not null references public.profiles(id) on delete cascade,
  permission_key text not null,
  created_at timestamptz not null default now(),
  primary key(user_id, permission_key)
);

create table if not exists public.attendance (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  work_date date not null default current_date,
  clock_in timestamptz,
  clock_out timestamptz,
  total_hours numeric(8,2),
  edited_by uuid references public.profiles(id),
  edited_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.overtime (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  work_date date not null default current_date,
  hours numeric(8,2) not null check(hours >= 0),
  hourly_rate numeric(12,2) not null check(hourly_rate >= 0),
  amount numeric(14,2) generated always as (hours * hourly_rate) stored,
  status text not null default 'pending' check(status in ('pending','approved','rejected')),
  approved_by uuid references public.profiles(id),
  approved_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.expenses (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  invoice_name text not null check(length(trim(invoice_name)) > 0),
  amount numeric(14,2) not null check(amount >= 0),
  spent_at timestamptz not null default now()
);

create table if not exists public.cash_records (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  amount numeric(14,2) not null check(amount >= 0),
  recorded_at timestamptz not null default now()
);

create table if not exists public.salary_advances (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  amount numeric(14,2) not null check(amount >= 0),
  advance_date date not null default current_date,
  note text,
  created_at timestamptz not null default now()
);

create table if not exists public.salary_settings (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  base_salary numeric(14,2) not null default 0 check(base_salary >= 0),
  overtime_hourly_rate numeric(12,2) not null default 0 check(overtime_hourly_rate >= 0),
  deduction numeric(14,2) not null default 0 check(deduction >= 0),
  updated_at timestamptz not null default now(),
  updated_by uuid references public.profiles(id)
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid references public.profiles(id),
  action text not null,
  table_name text,
  record_id text,
  details jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.app_settings (
  key text primary key,
  value text not null,
  updated_at timestamptz not null default now()
);

